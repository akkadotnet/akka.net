#nullable enable
using System;
using System.Buffers;
using System.Runtime.Serialization;
using Akka.Actor;
using Akka.Serialization;
using Akka.Serialization.V2;

namespace Akka.Cluster.Tools.Singleton.Serialization;

/// <summary>
/// Source-generated MessagePack version of the singleton hand-over protocol. The legacy id 14
/// remains readable; id 54 becomes the default writer only with akka.actor.serialization-v2 enabled.
/// Deserialization restores the original domain singleton instances rather than exposing wire mirrors.
/// </summary>
internal sealed class ClusterSingletonMessagePackSerializer : SerializerV2
{
    internal const int SerializerId = 54;
    internal const string HandOverToMeManifest = "A";
    internal const string HandOverInProgressManifest = "B";
    internal const string HandOverDoneManifest = "C";
    internal const string TakeOverFromMeManifest = "D";

    private readonly ClusterSingletonMessagePackCodec _codec;

    public ClusterSingletonMessagePackSerializer(ExtendedActorSystem system) : base(system)
    {
        _codec = new ClusterSingletonMessagePackCodec(system);
    }

    public override int Identifier => SerializerId;

    public override string Manifest(object obj) => obj switch
    {
        HandOverToMe => HandOverToMeManifest,
        HandOverInProgress => HandOverInProgressManifest,
        HandOverDone => HandOverDoneManifest,
        TakeOverFromMe => TakeOverFromMeManifest,
        _ => throw new ArgumentException($"Cannot serialize object of type [{obj.GetType()}] in [{GetType()}]", nameof(obj))
    };

    public override byte[] ToBinary(object obj)
    {
        _ = Manifest(obj);
        return [0x80]; // Every existing AllowEmpty wire record is an empty MessagePack map.
    }

    public override int Serialize(object obj, IBufferWriter<byte> writer)
    {
        _ = Manifest(obj);
        writer.GetSpan(1)[0] = 0x80;
        writer.Advance(1);
        return 1;
    }

    public override int SizeHint(object obj)
    {
        _ = Manifest(obj);
        return 1;
    }

    public override object FromBinary(byte[] bytes, string manifest) => bytes is [0x80]
        ? ReadSingleton(manifest)
        : Deserialize(new ReadOnlySequence<byte>(bytes), manifest);

    public override object Deserialize(ReadOnlySequence<byte> bytes, string manifest)
    {
        if (bytes.Length == 1 && bytes.FirstSpan is [0x80])
            return ReadSingleton(manifest);

        // Future fields and malformed records retain the generated reader's behavior.
        return _codec.Deserialize(bytes, manifest) switch
        {
            HandOverToMeWire => HandOverToMe.Instance,
            HandOverInProgressWire => HandOverInProgress.Instance,
            HandOverDoneWire => HandOverDone.Instance,
            TakeOverFromMeWire => TakeOverFromMe.Instance,
            var wire => throw new SerializationException($"Unknown singleton wire message [{wire.GetType()}]")
        };
    }

    private static object ReadSingleton(string manifest) => manifest switch
    {
        HandOverToMeManifest => HandOverToMe.Instance,
        HandOverInProgressManifest => HandOverInProgress.Instance,
        HandOverDoneManifest => HandOverDone.Instance,
        TakeOverFromMeManifest => TakeOverFromMe.Instance,
        _ => throw new SerializationException($"Unknown singleton manifest [{manifest}]")
    };
}

internal interface IClusterSingletonWireMessage
{
}

/// <summary>The generated byte codec is private to the wrapper and is never registered separately.</summary>
[AkkaSerializer<IClusterSingletonWireMessage>("akka-singleton-v2-codec", ClusterSingletonMessagePackSerializer.SerializerId)]
internal sealed partial class ClusterSingletonMessagePackCodec : AkkaSerializer
{
    public static partial SerializerDetails CreateSerializerDetails(ExtendedActorSystem system);
}

[AkkaSerializable(Manifest = ClusterSingletonMessagePackSerializer.HandOverToMeManifest, AllowEmpty = true)]
internal sealed record HandOverToMeWire : IClusterSingletonWireMessage;

[AkkaSerializable(Manifest = ClusterSingletonMessagePackSerializer.HandOverInProgressManifest, AllowEmpty = true)]
internal sealed record HandOverInProgressWire : IClusterSingletonWireMessage;

[AkkaSerializable(Manifest = ClusterSingletonMessagePackSerializer.HandOverDoneManifest, AllowEmpty = true)]
internal sealed record HandOverDoneWire : IClusterSingletonWireMessage;

[AkkaSerializable(Manifest = ClusterSingletonMessagePackSerializer.TakeOverFromMeManifest, AllowEmpty = true)]
internal sealed record TakeOverFromMeWire : IClusterSingletonWireMessage;
