#nullable enable
using System;
using System.Buffers;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Runtime.Serialization;
using Akka.Actor;
using Akka.Cluster.Serialization;
using Akka.Delivery;
using Akka.TestKit;
using Xunit;

namespace Akka.Cluster.Tests.Serialization;

[CollectionDefinition(Name, DisableParallelization = true)]
public sealed class DeliveryDynamicTypeLoadingCollection
{
    public const string Name = "Delivery.DynamicTypeLoading";
}

/// <summary>
/// A generated byte codec cannot make domain types discovered by name statically available.
/// Keep that boundary explicit, including when a JIT run already populated the factory cache.
/// </summary>
[Collection(DeliveryDynamicTypeLoadingCollection.Name)]
public sealed class ReliableDeliveryV2AotBoundarySpec : AkkaSpec
{
    private const string SwitchName = "Akka.DynamicTypeLoading";

    public ReliableDeliveryV2AotBoundarySpec(ITestOutputHelper output) : base(output)
    {
    }

    public static IEnumerable<object[]> ControlMessages()
    {
        yield return [new ProducerController.Ack(3L)];
        yield return [new ProducerController.Request(3L, 10L, true, false)];
        yield return [new ProducerController.Resend(4L)];
        yield return [new DurableProducerQueue.Confirmed(3L, "q1", 1000L)];
        yield return [new DurableProducerQueue.Cleanup(ImmutableHashSet.Create("q1"))];
    }

    public static IEnumerable<object[]> GenericMessages()
    {
        yield return [new ConsumerController.SequencedMessage<string>("producer", 1L, "payload", false, true, ActorRefs.Nobody)];
        yield return [new ProducerController.RegisterConsumer<string>(ActorRefs.Nobody)];
        yield return [new DurableProducerQueue.MessageSent<string>(1L, "payload", false, "q1", 1000L)];
        yield return [new DurableProducerQueue.State<string>(1L, 0L,
            ImmutableDictionary<string, (long, long)>.Empty,
            ImmutableList<DurableProducerQueue.MessageSent<string>>.Empty)];
    }

    [Theory(DisplayName = "Should_RoundTripControlMessages_When_DynamicTypeLoadingIsDisabled")]
    [MemberData(nameof(ControlMessages))]
    public void Should_RoundTripControlMessages_When_DynamicTypeLoadingIsDisabled(object message)
    {
        WithDynamicTypeLoading(false, () =>
        {
            var serializer = new ReliableDeliveryMessagePackSerializer((ExtendedActorSystem)Sys);
            var manifest = serializer.Manifest(message);
            var bytes = serializer.ToBinary(message);
            var decoded = serializer.FromBinary(bytes, manifest);
            if (message is DurableProducerQueue.Cleanup cleanup)
                Assert.True(cleanup.ConfirmationQualifiers.SetEquals(
                    Assert.IsType<DurableProducerQueue.Cleanup>(decoded).ConfirmationQualifiers));
            else
                Assert.Equal(message, decoded);
        });
    }

    [Theory(DisplayName = "Should_RejectGenericWrites_When_DynamicTypeLoadingIsDisabled")]
    [MemberData(nameof(GenericMessages))]
    public void Should_RejectGenericWrites_When_DynamicTypeLoadingIsDisabled(object message)
    {
        WithDynamicTypeLoading(false, () =>
        {
            var serializer = new ReliableDeliveryMessagePackSerializer((ExtendedActorSystem)Sys);
            var error = Assert.Throws<SerializationException>(() => serializer.ToBinary(message));
            Assert.Contains(SwitchName, error.Message);
            Assert.Contains("runtime type reconstruction", error.Message);

            var writer = new ArrayBufferWriter<byte>();
            Assert.Throws<SerializationException>(() => serializer.Serialize(message, writer));
            Assert.Equal(0, writer.WrittenCount);
        });
    }

    [Theory(DisplayName = "Should_RejectCachedGenericReads_When_DynamicTypeLoadingIsDisabled")]
    [MemberData(nameof(GenericMessages))]
    public void Should_RejectCachedGenericReads_When_DynamicTypeLoadingIsDisabled(object message)
    {
        var serializer = new ReliableDeliveryMessagePackSerializer((ExtendedActorSystem)Sys);
        byte[] bytes = [];
        var manifest = serializer.Manifest(message);

        WithDynamicTypeLoading(true, () =>
        {
            bytes = serializer.ToBinary(message);
            Assert.Equal(message.GetType(), serializer.FromBinary(bytes, manifest).GetType());
        });

        WithDynamicTypeLoading(false, () =>
        {
            var error = Assert.Throws<SerializationException>(() => serializer.FromBinary(bytes, manifest));
            Assert.Contains(SwitchName, error.Message);
        });
    }

    private static void WithDynamicTypeLoading(bool enabled, Action action)
    {
        var previous = !AppContext.TryGetSwitch(SwitchName, out var value) || value;
        AppContext.SetSwitch(SwitchName, enabled);
        try
        {
            action();
        }
        finally
        {
            AppContext.SetSwitch(SwitchName, previous);
        }
    }
}
